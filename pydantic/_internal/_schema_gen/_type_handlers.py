"""The base classes for type handlers."""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import TYPE_CHECKING, Any, ClassVar

from pydantic_core import CoreSchema

if TYPE_CHECKING:
    from .._generate_schema import GenerateSchema
    from ._annotations_handler import AnnotationsHandler
    from ._conditions import Condition


class BaseTypeHandler(ABC):
    """The base class for type handlers.

    A type handler generates the core schema for a type, together with the metadata attached to it that it knows about.
    This means the smallest unit of work during schema generation is a type *and* its known metadata.

    Type handlers shouldn't subclass this class directly, but `TypeHandler` or `GenericTypeHandler`.

    A type handler instance is created each time a type is matched, and shouldn't hold any state.
    """

    __slots__ = ('schema_generator',)

    match_condition: ClassVar[Condition]
    """The condition used to determine whether this type handler should be used for a type."""

    known_metadata: ClassVar[frozenset[type[Any]]] = frozenset()
    """The metadata classes that this type handler knows how to apply (e.g. `annotated_types.Gt`, `pydantic.Strict`).

    Only the metadata elements of these classes are provided by the annotations handler. The other metadata
    elements are applied by Pydantic after the core schema is generated by the type handler.
    """

    is_referenceable: ClassVar[bool] = False
    """Whether `get_reference()` is implemented (set automatically)."""

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        cls.is_referenceable = cls.get_reference is not BaseTypeHandler.get_reference

    def __init__(self, schema_generator: GenerateSchema) -> None:
        self.schema_generator = schema_generator

    def generate_schema(self, tp: Any, /) -> CoreSchema:
        """Delegate the core schema generation of `tp` back to Pydantic (e.g. for type arguments)."""
        return self.schema_generator.generate_schema(tp)

    def get_reference(self, obj: Any, origin: Any | None) -> str | None:
        """Return a unique reference for the type, if it can be referenced (e.g. because it can be recursive).

        If implemented, Pydantic takes care of detecting cycles and reusing the generated core schema
        when the type is encountered multiple times. The type handler should *not* set the reference
        on the core schema, as Pydantic does it.
        """
        return None

    @abstractmethod
    def _generate_schema(self, obj: Any, origin: Any | None, annotations_handler: AnnotationsHandler) -> CoreSchema:
        """Generate the core schema of `obj`.

        Args:
            obj: The type to generate the core schema for (e.g. `list[int]`).
            origin: The origin of the type if parameterized (e.g. `list`), `None` otherwise.
            annotations_handler: The annotations handler, giving access to the known metadata.
        """


class TypeHandler(BaseTypeHandler, ABC):
    """The base class for type handlers of non-generic types."""

    __slots__ = ()

    def _generate_schema(self, obj: Any, origin: Any | None, annotations_handler: AnnotationsHandler) -> CoreSchema:
        return self.handle_type(obj, annotations_handler)

    @abstractmethod
    def handle_type(self, type: Any, annotations_handler: AnnotationsHandler) -> CoreSchema:
        """Generate the core schema for `type`.

        Args:
            type: The type to generate the core schema for. Can be used if the `match_condition` matches multiple types.
            annotations_handler: The annotations handler, giving access to the known metadata.
        """


class GenericTypeHandler(BaseTypeHandler, ABC):
    """The base class for type handlers of generic types.

    Pydantic takes care of extracting the type arguments (and resolving forward references in them).
    """

    __slots__ = ()

    default_args: ClassVar[tuple[Any, ...]] = ()
    """The type arguments to use if the type is unparameterized (e.g. `(Any,)` for `list`)."""

    def _generate_schema(self, obj: Any, origin: Any | None, annotations_handler: AnnotationsHandler) -> CoreSchema:
        if origin is None:
            return self.handle_type(obj, self.default_args, annotations_handler)
        args = self.schema_generator._get_args_resolving_forward_refs(obj)
        return self.handle_type(origin, args or self.default_args, annotations_handler)

    @abstractmethod
    def handle_type(self, type: Any, args: tuple[Any, ...], annotations_handler: AnnotationsHandler) -> CoreSchema:
        """Generate the core schema for `type`.

        Args:
            type: The generic type to generate the core schema for (e.g. `list` for `list[int]`).
            args: The type arguments (e.g. `(int,)` for `list[int]`), or `default_args` if unparameterized.
            annotations_handler: The annotations handler, giving access to the known metadata.
        """
